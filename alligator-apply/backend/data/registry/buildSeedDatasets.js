// Deduplicate greenhouse by boardToken (keep first / highest priority)
function dedupeByToken(rows) {
  const seen = new Map();
  for (const r of rows) {
    const key = r.boardToken.toLowerCase();
    if (!seen.has(key)) seen.set(key, r);
  }
  return [...seen.values()];
}

