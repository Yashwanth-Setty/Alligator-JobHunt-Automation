function dedupeWorkday(rows) {
  const seen = new Map();
  for (const r of rows) {
    const payload = r.connectionPayload;
    const key = `${payload.tenant}::${payload.site}`.toLowerCase();
    if (!seen.has(key)) seen.set(key, r);
  }
  return [...seen.values()];
}

